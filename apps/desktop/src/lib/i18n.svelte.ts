const dictionaries: Record<Lang, Dict> = { it, en };

export const i18n = $state<{ lang: Lang }>({ lang: "it" });

/** Etichetta localizzata dello stato di un motore (mai stringhe grezze in UI). */
export function engineStateLabel(status: string | null | undefined): string {
  switch (status) {
    case "available":
      return t("engines.statusAvailable");
    case "verified":
      return t("engines.statusVerified");
    case "experimental":
      return t("engines.statusExperimental");
    case "unavailable":
      return t("engines.statusUnavailable");
    default:
      return t("engines.statusError");
  }
}

export function setLang(lang: Lang): void {
  i18n.lang = lang;
  try {
    document.documentElement.lang = lang;
  } catch {
    /* ambiente non browser */
  }
}

export function currentLang(): Lang {
  return i18n.lang;
}

/** Traduzione con fallback alla chiave: le chiavi mancanti si vedono subito. */
export function t(key: string, vars?: Record<string, string | number>): string {
  const dict = dictionaries[i18n.lang] ?? it;
  let value = dict[key] ?? it[key] ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}

/** Messaggio localizzato per un errore host, con fallback al messaggio ricevuto. */
export function hostErrorMessage(err: { code?: string; message?: string } | null | undefined): string {
  if (!err) return t("common.unknownError");
  if (err.code && it[`errors.${err.code}`]) return t(`errors.${err.code}`);
  return err.message ?? t("common.unknownError");
}
